/// Ray-casting point-in-polygon test against one ring.
fn in_ring(lon: f64, lat: f64, ring: &[(f32, f32)]) -> bool {
    let mut inside = false;
    let mut j = ring.len() - 1;
    for i in 0..ring.len() {
        let (xi, yi) = (ring[i].0 as f64, ring[i].1 as f64);
        let (xj, yj) = (ring[j].0 as f64, ring[j].1 as f64);
        if ((yi > lat) != (yj > lat)) && (lon < (xj - xi) * (lat - yi) / (yj - yi) + xi) {
            inside = !inside;
        }
        j = i;
    }
    inside
}

pub fn point_in_sweden(lon: f64, lat: f64) -> bool {
    RINGS.iter().any(|ring| in_ring(lon, lat, ring))
}

pub fn lonlat_to_pixel(lon: f64, lat: f64) -> (f32, f32) {
    let x = (lon - LON_MIN) / (LON_MAX - LON_MIN) * IMG_W as f64;
    let y = (LAT_MAX - lat) / (LAT_MAX - LAT_MIN) * IMG_H as f64;
    (x as f32, y as f32)
}

pub fn pixel_to_lonlat(x: f32, y: f32) -> (f64, f64) {
    let lon = LON_MIN + (x as f64 / IMG_W as f64) * (LON_MAX - LON_MIN);
    let lat = LAT_MAX - (y as f64 / IMG_H as f64) * (LAT_MAX - LAT_MIN);
    (lon, lat)
}

const DARK_LAND: [u8; 4] = [31, 71, 97, 255];
const DARK_COAST: [u8; 4] = [137, 180, 250, 255];
const LIGHT_LAND: [u8; 4] = [172, 192, 210, 255];
const LIGHT_COAST: [u8; 4] = [30, 102, 245, 255];

/// Rasterize the outline into an RGBA8 buffer: filled land, a lighter
/// coastline ring, transparent sea so the screen background shows through.
/// Uses a scanline fill (one pass per row across all rings, even-odd rule)
/// rather than a per-pixel point-in-polygon test — the polygons here have
/// ~300 points total, and a naive per-pixel test would be edges × pixels.
pub fn rasterize(dark: bool) -> Vec<u8> {
    let (land, coast) = if dark {
        (DARK_LAND, DARK_COAST)
    } else {
        (LIGHT_LAND, LIGHT_COAST)
    };

    let mut inside = vec![false; (IMG_W * IMG_H) as usize];
    for y in 0..IMG_H {
        let (_, lat) = pixel_to_lonlat(0.0, y as f32 + 0.5);
        let mut crossings: Vec<f64> = Vec::new();
        for ring in RINGS {
            let mut j = ring.len() - 1;
            for i in 0..ring.len() {
                let (xi, yi) = (ring[i].0 as f64, ring[i].1 as f64);
                let (xj, yj) = (ring[j].0 as f64, ring[j].1 as f64);
                if (yi > lat) != (yj > lat) {
                    crossings.push((xj - xi) * (lat - yi) / (yj - yi) + xi);
                }
                j = i;
            }
        }
        crossings.sort_by(|a, b| a.partial_cmp(b).unwrap());

        for pair in crossings.chunks_exact(2) {
            let (x0, _) = lonlat_to_pixel(pair[0], lat);
            let (x1, _) = lonlat_to_pixel(pair[1], lat);
            let start = x0.min(x1).round().max(0.0) as u32;
            let end = (x0.max(x1).round() as i32).clamp(0, IMG_W as i32) as u32;
            for x in start..end.min(IMG_W) {
                inside[(y * IMG_W + x) as usize] = true;
            }
        }
    }

    let is_inside = |x: i32, y: i32| -> bool {
        if x < 0 || y < 0 || x >= IMG_W as i32 || y >= IMG_H as i32 {
            false
        } else {
            inside[(y as u32 * IMG_W + x as u32) as usize]
        }
    };

    let mut pixels = Vec::with_capacity((IMG_W * IMG_H * 4) as usize);
    for y in 0..IMG_H as i32 {
        for x in 0..IMG_W as i32 {
            if !is_inside(x, y) {
                pixels.extend_from_slice(&[0, 0, 0, 0]);
                continue;
            }
            let on_coast = !is_inside(x - 1, y)
                || !is_inside(x + 1, y)
                || !is_inside(x, y - 1)
                || !is_inside(x, y + 1);
            pixels.extend_from_slice(if on_coast { &coast } else { &land });
        }
    }
    pixels
}
